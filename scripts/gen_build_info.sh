#!/bin/sh
# Writes the header that supplies the About box's "Last Modified" date, taken
# from the last commit so nobody has to remember to bump a literal. Called from
# OpenHydroQual.pro at qmake time.
#
#   gen_build_info.sh <output-header> <source-tree>
#
# If git is unavailable or this is not a repository, no macro is defined and
# mainwindow.cpp falls back to the compiler's __DATE__.
set -e
out="$1"
src="$2"

date_str=$(git -C "$src" log -1 --format=%ad --date="format:%B %d, %Y" 2>/dev/null || true)

{
    echo "/* Generated by scripts/gen_build_info.sh -- do not edit. */"
    echo "#pragma once"
    if [ -n "$date_str" ]; then
        echo "#define OHQ_LAST_MODIFIED \"$date_str\""
    fi
} > "$out"
